"""
Buckling interaction curves for proportional in-plane loading.

The multimode HOST buckling problem is solved for

    (Nx, Ny, Nxy)
        =
    lambda * (Nx_ref, Ny_ref, Nxy_ref).

Interaction curves are generated by varying the reference loading
direction while solving for the critical multiplier lambda.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from host.multimode_buckling import (
    solve_directional_multimode_buckling,
    MultimodeBucklingResult,
    solve_multimode_buckling,
)


@dataclass(frozen=True)
class BucklingInteractionPoint:
    parameter: float

    Nx_ref: float
    Ny_ref: float
    Nxy_ref: float

    load_factor: float

    Nx_cr: float
    Ny_cr: float
    Nxy_cr: float

    result: MultimodeBucklingResult


def proportional_buckling_point(
    K_hsdt,
    a,
    b,
    *,
    Nx_ref,
    Ny_ref,
    Nxy_ref,
    parameter=np.nan,
    max_m=16,
    max_n=16,
):
    """
    Solve one proportional combined-load buckling state.
    """

    result = solve_multimode_buckling(
        K_hsdt,
        a=a,
        b=b,
        Nx_ref=float(Nx_ref),
        Ny_ref=float(Ny_ref),
        Nxy_ref=float(Nxy_ref),
        max_m=max_m,
        max_n=max_n,
    )

    lam = float(
        result.load_factor
    )

    return BucklingInteractionPoint(
        parameter=float(parameter),

        Nx_ref=float(Nx_ref),
        Ny_ref=float(Ny_ref),
        Nxy_ref=float(Nxy_ref),

        load_factor=lam,

        Nx_cr=lam * float(Nx_ref),
        Ny_cr=lam * float(Ny_ref),
        Nxy_cr=lam * float(Nxy_ref),

        result=result,
    )


def nx_nxy_interaction(
    K_hsdt,
    a,
    b,
    *,
    angles_deg=None,
    max_m=16,
    max_n=16,
):
    """
    Nx-Nxy interaction.

    Reference direction:

        Nx_ref   = cos(theta)
        Ny_ref   = 0
        Nxy_ref  = sin(theta)

    with -90 <= theta <= 90 degrees.
    """

    if angles_deg is None:
        angles_deg = np.linspace(
            -90.0,
            90.0,
            73,
        )

    points = []

    for angle in angles_deg:
        theta = np.deg2rad(
            float(angle)
        )

        Nx_ref = np.cos(theta)
        Nxy_ref = np.sin(theta)

        # Remove numerical remnants at exact endpoints.
        if abs(Nx_ref) < 1.0e-14:
            Nx_ref = 0.0

        if abs(Nxy_ref) < 1.0e-14:
            Nxy_ref = 0.0

        points.append(
            proportional_buckling_point(
                K_hsdt,
                a,
                b,
                Nx_ref=Nx_ref,
                Ny_ref=0.0,
                Nxy_ref=Nxy_ref,
                parameter=angle,
                max_m=max_m,
                max_n=max_n,
            )
        )

    return tuple(points)


