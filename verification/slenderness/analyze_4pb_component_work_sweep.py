#!/usr/bin/env python3
"""
Analyze the component-wise 3-D stress-strain work over the HOST 4PB
deep-to-slender sweep.

This is a normal CPython script.  It scans the scratch run root for the six
campaign FE cases, reads post/component_work.json generated by
extract_4pb_component_work.py, merges those data with the HOST 1-D/2-D sweep,
and writes a compact mechanism-diagnostic table.

Primary diagnostic question
---------------------------
Does the HOST-to-3D-FE deflection discrepancy decay together with transverse
normal work/strain measures (S33*E33, E33), while the model becomes slender?

A positive correlation is evidence, not proof, that transverse-normal
deformation is one of the missing thick/deep 3-D mechanisms.  The component
work terms are signed partitions and must not be interpreted as independent
positive modal energies in the anisotropic core.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
from pathlib import Path
from typing import Dict, List, Sequence

import numpy as np


DEFAULT_N_SHEAR = (6, 9, 12, 18, 24, 30)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--run-root",
        type=Path,
        default=Path(r"C:\AbaqusScratch\HOST\4pb_homogenized"),
    )

    parser.add_argument(
        "--slenderness-json",
        type=Path,
        default=Path(
            "verification/slenderness/results/"
            "gyroid_rd12_initial/slenderness_sweep.json"
        ),
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path(
            "verification/slenderness/results/"
            "gyroid_rd12_initial/component_work"
        ),
    )

    parser.add_argument(
        "--n-shear",
        default=",".join(str(v) for v in DEFAULT_N_SHEAR),
    )

    parser.add_argument("--element-type", default="C3D20R")
    parser.add_argument("--ne-cell", type=int, default=2)
    parser.add_argument("--face-ne-z", type=int, default=2)
    parser.add_argument("--fixture-mode", default="section_distributing")
    parser.add_argument("--domain-mode", default="quarter_xy")

    return parser.parse_args()


def load_json(path: Path) -> dict:
    with path.open("r", encoding="utf-8") as handle:
        return json.load(handle)


def parse_ints(text: str) -> tuple[int, ...]:
    return tuple(
        int(token.strip())
        for token in str(text).split(",")
        if token.strip()
    )


def find_cases(
    run_root: Path,
    n_shear_values: Sequence[int],
    *,
    element_type: str,
    ne_cell: int,
    face_ne_z: int,
    fixture_mode: str,
    domain_mode: str,
) -> Dict[int, dict]:
    wanted = set(int(v) for v in n_shear_values)
    candidates: Dict[int, List[dict]] = {v: [] for v in wanted}

    for case_dir in run_root.iterdir():
        if not case_dir.is_dir():
            continue

        manifest_path = case_dir / "manifest.json"
        component_path = case_dir / "post" / "component_work.json"

        if not manifest_path.is_file() or not component_path.is_file():
            continue

        try:
            manifest = load_json(manifest_path)
            n_shear = int(manifest["geometry"]["n_shear"])
        except Exception:
            continue

        if n_shear not in wanted:
            continue

        mesh = manifest.get("mesh", {})
        fixture = manifest.get("fixture", {})
        domain = manifest.get("domain", {})

        if str(mesh.get("element_type", "")).upper() != element_type.upper():
            continue
        if int(mesh.get("core_elements_per_cell_edge", -1)) != int(ne_cell):
            continue
        if int(mesh.get("face_elements_through_thickness", -1)) != int(face_ne_z):
            continue
        if str(fixture.get("mode", "")).lower() != fixture_mode.lower():
            continue
        if str(domain.get("mode", "")).lower() != domain_mode.lower():
            continue

        candidates[n_shear].append(
            {
                "case_dir": case_dir,
                "manifest": manifest,
                "component": load_json(component_path),
                "mtime": component_path.stat().st_mtime,
            }
        )

    selected = {}

    for n_shear, items in candidates.items():
        if not items:
            continue

        items.sort(key=lambda item: item["mtime"], reverse=True)
        selected[n_shear] = items[0]

    return selected


def theory_rows(path: Path) -> Dict[int, dict]:
    if not path.is_file():
        return {}

    report = load_json(path)

    rows = {}
    for row in report.get("rows", []):
        try:
            rows[int(row["n_shear"])] = row
        except Exception:
            pass

    return rows


def region_component(
    component_report: dict,
    region: str,
    component: str,
) -> dict:
    return component_report["regions"][region]["components"][component]


def signed_fraction(component_report: dict, region: str, component: str) -> float:
    return float(
        region_component(
            component_report,
            region,
            component,
        )["signed_fraction_of_component_work_sum"]
    )


def reconstructed_work(component_report: dict, region: str, component: str) -> float:
    return float(
        region_component(
            component_report,
            region,
            component,
        )["full_model_reconstructed_work_Nmm"]
    )


def pearson(x: Sequence[float], y: Sequence[float]) -> float:
    x_arr = np.asarray(x, dtype=float)
    y_arr = np.asarray(y, dtype=float)

    if x_arr.size < 2:
        return float("nan")

    if np.std(x_arr) == 0.0 or np.std(y_arr) == 0.0:
        return float("nan")

    return float(np.corrcoef(x_arr, y_arr)[0, 1])


def maybe_plot(rows: List[dict], output_dir: Path) -> list[str]:
    try:
        import matplotlib.pyplot as plt
    except Exception:
        return []

    paths = []

    a_over_h = np.asarray([row["a_over_h"] for row in rows], dtype=float)
    err_1d = np.asarray(
        [100.0 * abs(row["HOST_1D_vs_FE_relative"]) for row in rows],
        dtype=float,
    )
    err_2d = np.asarray(
        [100.0 * abs(row["HOST_2D_vs_FE_relative"]) for row in rows],
        dtype=float,
    )

    fig = plt.figure()
    ax = fig.add_subplot(111)
    ax.plot(a_over_h, err_1d, marker="o", label="HOST 1D vs FE")
    ax.plot(a_over_h, err_2d, marker="s", label="HOST 2D vs FE")
    ax.set_xlabel("a/h")
    ax.set_ylabel("absolute deflection error [%]")
    ax.grid(True)
    ax.legend()
    fig.tight_layout()

    path = output_dir / "host_error_vs_slenderness.png"
    fig.savefig(path, dpi=180)
    plt.close(fig)
    paths.append(str(path))

    fig = plt.figure()
    ax = fig.add_subplot(111)
    ax.plot(
        a_over_h,
        100.0 * np.asarray([row["CORE_U33_fraction"] for row in rows]),
        marker="o",
        label="core U33",
    )
    ax.plot(
        a_over_h,
        100.0 * np.asarray([row["CORE_U13_fraction"] for row in rows]),
        marker="s",
        label="core U13",
    )
    ax.plot(
        a_over_h,
        100.0 * np.asarray([row["CORE_BULK_U33_fraction"] for row in rows]),
        marker="^",
        label="core bulk U33",
    )
    ax.set_xlabel("a/h")
    ax.set_ylabel("signed component-work fraction [%]")
    ax.grid(True)
    ax.legend()
    fig.tight_layout()

    path = output_dir / "component_work_fraction_vs_slenderness.png"
    fig.savefig(path, dpi=180)
    plt.close(fig)
    paths.append(str(path))

    return paths


def main() -> int:
    args = parse_args()

    run_root = args.run_root.resolve()
    slenderness_path = args.slenderness_json.resolve()
    output_dir = args.output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    n_shear_values = parse_ints(args.n_shear)

    selected = find_cases(
        run_root,
        n_shear_values,
        element_type=args.element_type,
        ne_cell=args.ne_cell,
        face_ne_z=args.face_ne_z,
        fixture_mode=args.fixture_mode,
        domain_mode=args.domain_mode,
    )

    theory = theory_rows(slenderness_path)

    rows = []

    for n_shear in n_shear_values:
        if n_shear not in selected:
            continue

        item = selected[n_shear]
        component = item["component"]

        geometry = component["geometry"]
        fe_w = component.get("midspan", {}).get("abs_U3_midplane_avg_mm")

        theory_row = theory.get(n_shear, {})

        host_1d = theory_row.get("HOST_1D_abs_w_mid_mm")
        host_2d = theory_row.get("HOST_2D_abs_w_mid_width_average_mm")

        if host_1d in ("", None) or host_2d in ("", None) or fe_w in ("", None):
            raise RuntimeError(
                "Missing HOST/FE deflection for N_SHEAR={}. "
                "Re-run the slenderness comparison and component extractor."
                .format(n_shear)
            )

        host_1d = float(host_1d)
        host_2d = float(host_2d)
        fe_w = float(fe_w)

        core_33 = region_component(component, "CORE", "33")
        core_13 = region_component(component, "CORE", "13")
        core_bulk_33 = region_component(component, "CORE_BULK", "33")
        core_fixture_33 = region_component(component, "CORE_FIXTURE_BANDS", "33")

        row = {
            "n_shear": int(n_shear),
            "a_over_h": float(geometry["a_over_h"]),
            "S_over_h": float(geometry["S_over_h"]),
            "HOST_1D_abs_w_mid_mm": host_1d,
            "HOST_2D_abs_w_mid_mm": host_2d,
            "FE_3D_abs_w_mid_mm": fe_w,
            "HOST_1D_vs_FE_relative": (host_1d - fe_w) / fe_w,
            "HOST_2D_vs_FE_relative": (host_2d - fe_w) / fe_w,
            "ALL_U33_fraction": signed_fraction(component, "ALL", "33"),
            "ALL_U13_fraction": signed_fraction(component, "ALL", "13"),
            "CORE_U11_fraction": signed_fraction(component, "CORE", "11"),
            "CORE_U22_fraction": signed_fraction(component, "CORE", "22"),
            "CORE_U33_fraction": signed_fraction(component, "CORE", "33"),
            "CORE_U12_fraction": signed_fraction(component, "CORE", "12"),
            "CORE_U13_fraction": signed_fraction(component, "CORE", "13"),
            "CORE_U23_fraction": signed_fraction(component, "CORE", "23"),
            "CORE_BULK_U33_fraction": signed_fraction(
                component,
                "CORE_BULK",
                "33",
            ),
            "CORE_FIXTURE_U33_fraction": signed_fraction(
                component,
                "CORE_FIXTURE_BANDS",
                "33",
            ),
            "CORE_U33_full_Nmm": reconstructed_work(component, "CORE", "33"),
            "CORE_U13_full_Nmm": reconstructed_work(component, "CORE", "13"),
            "CORE_BULK_U33_full_Nmm": reconstructed_work(
                component,
                "CORE_BULK",
                "33",
            ),
            "CORE_FIXTURE_U33_full_Nmm": reconstructed_work(
                component,
                "CORE_FIXTURE_BANDS",
                "33",
            ),
            "CORE_E33_rms": float(core_33["strain_rms"]),
            "CORE_E33_max_abs": float(core_33["strain_max_abs"]),
            "CORE_S33_rms_MPa": float(core_33["stress_rms_MPa"]),
            "CORE_S33_max_abs_MPa": float(core_33["stress_max_abs_MPa"]),
            "CORE_E13_rms": float(core_13["strain_rms"]),
            "CORE_S13_rms_MPa": float(core_13["stress_rms_MPa"]),
            "CORE_BULK_E33_rms": float(core_bulk_33["strain_rms"]),
            "CORE_BULK_S33_rms_MPa": float(core_bulk_33["stress_rms_MPa"]),
            "CORE_FIXTURE_E33_rms": float(core_fixture_33["strain_rms"]),
            "CORE_FIXTURE_S33_rms_MPa": float(core_fixture_33["stress_rms_MPa"]),
            "component_work_closure_relative_error": float(
                component["qa"]["component_work_vs_SENER_relative_error"]
            ),
            "case_hash": component["case"].get("case_hash"),
            "case_path": component["case"]["path"],
        }

        rows.append(row)

    if len(rows) != len(n_shear_values):
        missing = sorted(set(n_shear_values) - {row["n_shear"] for row in rows})
        raise RuntimeError(
            "Found component-work results for {}/{} cases. Missing N_SHEAR={}"
            .format(
                len(rows),
                len(n_shear_values),
                missing,
            )
        )

    rows.sort(key=lambda row: row["a_over_h"])

    csv_path = output_dir / "component_work_slenderness.csv"
    json_path = output_dir / "component_work_slenderness.json"

    with csv_path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)

    abs_error = [
        abs(float(row["HOST_1D_vs_FE_relative"]))
        for row in rows
    ]

    correlations = {
        "abs_HOST1D_error_vs_CORE_U33_fraction": pearson(
            abs_error,
            [abs(float(row["CORE_U33_fraction"])) for row in rows],
        ),
        "abs_HOST1D_error_vs_CORE_BULK_U33_fraction": pearson(
            abs_error,
            [abs(float(row["CORE_BULK_U33_fraction"])) for row in rows],
        ),
        "abs_HOST1D_error_vs_CORE_E33_rms": pearson(
            abs_error,
            [float(row["CORE_E33_rms"]) for row in rows],
        ),
        "abs_HOST1D_error_vs_CORE_U13_fraction": pearson(
            abs_error,
            [abs(float(row["CORE_U13_fraction"])) for row in rows],
        ),
    }

    plots = maybe_plot(rows, output_dir)

    report = {
        "schema": "host_4pb_component_work_slenderness_v1",
        "warning": (
            "Component work terms 0.5*Sij*Eij are signed diagnostic partitions, "
            "not independent positive modal energies for anisotropic material."
        ),
        "rows": rows,
        "correlations": correlations,
        "plots": plots,
    }

    with json_path.open("w", encoding="utf-8") as handle:
        json.dump(report, handle, indent=2)
        handle.write("\n")

    print()
    print("=" * 116)
    print("HOST 4PB COMPONENT-WORK / SLENDERNESS DIAGNOSTIC")
    print("=" * 116)
    print(
        "{:>6s} {:>8s} {:>10s} {:>10s} {:>10s} {:>10s} {:>11s} {:>11s}".format(
            "N_A",
            "a/h",
            "|e1D|%",
            "core U33%",
            "bulk U33%",
            "core U13%",
            "E33 rms",
            "S33 rms",
        )
    )

    for row in rows:
        print(
            "{:6d} {:8.3f} {:10.4f} {:10.4f} {:10.4f} {:10.4f} {:11.4e} {:11.4e}".format(
                int(row["n_shear"]),
                float(row["a_over_h"]),
                100.0 * abs(float(row["HOST_1D_vs_FE_relative"])),
                100.0 * float(row["CORE_U33_fraction"]),
                100.0 * float(row["CORE_BULK_U33_fraction"]),
                100.0 * float(row["CORE_U13_fraction"]),
                float(row["CORE_E33_rms"]),
                float(row["CORE_S33_rms_MPa"]),
            )
        )

    print()
    print("Pearson correlations with |HOST 1D error|:")
    for key, value in correlations.items():
        print("  {:50s} {:+.6f}".format(key, value))

    max_closure = max(
        float(row["component_work_closure_relative_error"])
        for row in rows
    )
    print()
    print("Max component-work closure error: {:.3e}".format(max_closure))
    print("Wrote:")
    print(" ", csv_path)
    print(" ", json_path)
    for path in plots:
        print(" ", path)
    print("=" * 116)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
